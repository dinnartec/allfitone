/**
 * Turns the authored wave into the curation block that loads it.
 *
 * Two files meet here. `wave.json` says which exercises were chosen and carries their
 * equipment and muscles already translated through `mapping.ts`; `wave-1.ts` carries
 * the Spanish a person wrote. Neither is complete on its own, and **the join is
 * checked rather than assumed**: an exercise chosen but not authored, or authored but
 * not chosen, stops the run. Without that a movement could reach the catalogue with
 * somebody else's muscles attached and nothing would say so.
 *
 * Ordinals continue from the 38 already published and are assigned in the order the
 * chosen list is written. **The ordinal is the identity**, so once this file has run
 * against a real database the order in `wave.json` must not change — which is why the
 * selection sorts deterministically rather than by anything that could drift.
 *
 * It writes `003_movement_wave_1.sql`, which is generated and committed: the same
 * arrangement as the demonstrations, so what runs against production is reviewable as
 * a diff rather than as a program somebody has to trust.
 */

import type { Chosen } from './selection.js'
import * as authored from './wave-1.js'
import type { Authored } from './wave-1.js'

const here = (name: string) => new URL(`./${name}`, import.meta.url).pathname

/** The last ordinal `001_global_training_catalogue.sql` publishes. */
const ALREADY_CURATED = 38

const CURATION = new URL('../003_movement_wave_1.sql', import.meta.url).pathname

function everyAuthored(): readonly Authored[] {
  return Object.values(authored).filter(Array.isArray).flat() as Authored[]
}

/** Single quotes are the only thing that could break out of a literal here. */
function sql(value: string): string {
  return `'${value.replace(/'/g, "''")}'`
}

function array(values: readonly string[]): string {
  return `array[${values.map(sql).join(',')}]`
}

interface Joined extends Authored {
  readonly ordinal: number
  readonly equipment: readonly string[]
  readonly muscles: readonly string[]
}

export function join(chosen: readonly Chosen[], written: readonly Authored[]): readonly Joined[] {
  const byId = new Map(written.map((one) => [one.id, one]))
  const missing = chosen.filter((one) => !byId.has(one.exerciseId))
  if (missing.length > 0) {
    throw new Error(
      `${missing.length} chosen but not authored, starting with ${missing
        .slice(0, 5)
        .map((one) => `${one.exerciseId} (${one.source})`)
        .join(', ')}`,
    )
  }

  const wanted = new Set(chosen.map((one) => one.exerciseId))
  const extra = written.filter((one) => !wanted.has(one.id))
  if (extra.length > 0) {
    throw new Error(`authored but not chosen: ${extra.map((one) => one.slug).join(', ')}`)
  }

  const slugs = new Set<string>()
  const names = new Set<string>()
  return chosen.map((one, index) => {
    const written = byId.get(one.exerciseId)
    if (!written) throw new Error(`${one.exerciseId} vanished between the two passes`)
    if (slugs.has(written.slug)) throw new Error(`slug ${written.slug} is used twice`)
    if (names.has(written.name.toLowerCase())) throw new Error(`name ${written.name} is used twice`)
    slugs.add(written.slug)
    names.add(written.name.toLowerCase())
    return {
      ...written,
      ordinal: ALREADY_CURATED + index + 1,
      equipment: one.equipment,
      muscles: one.muscles,
    }
  })
}

function render(rows: readonly Joined[]): string {
  const movements = rows
    .map((one) => `  (${one.ordinal}, ${sql(one.slug)}, ${sql(one.discipline)}, ${sql(one.name)})`)
    .join(',\n')
  const aliases = rows.map((one) => `  (${sql(one.slug)}, ${array(one.aliases)})`).join(',\n')
  const muscles = rows.map((one) => `  (${sql(one.slug)}, ${array(one.muscles)})`).join(',\n')
  const equipment = rows.map((one) => `  (${sql(one.slug)}, ${array(one.equipment)})`).join(',\n')
  const steps = rows
    .flatMap((one) =>
      one.steps.map((text, index) => `  (${sql(one.slug)}, ${index + 1}, ${sql(text)})`),
    )
    .join(',\n')

  return `-- Wave one of the movement catalogue: ${rows.length} movements, ordinals ${rows[0]?.ordinal} to ${rows[rows.length - 1]?.ordinal}.
--
-- **Generated by \`curation/import/wave.ts\`. Do not edit.** The Spanish lives in
-- \`curation/import/wave-1.ts\`, where a person wrote it; the muscles and equipment come
-- from \`wave.json\`, which translated the source's vocabulary through an explicit map.
-- Editing here would put the file and its sources out of step with nothing to say so.
--
-- Run after \`001_global_training_catalogue.sql\`: the vocabularies it publishes are
-- what every row below refers to, and the ordinals continue from the 38 it creates.
--
-- The ordinal is the identity and is never renumbered. A slug that has shipped keeps
-- its number forever, because a program version points at it.

\\set ON_ERROR_STOP on

begin;

select set_config('app.planning_publication', 'true', true);
select set_config('app.actor_kind', 'person', true);
select set_config('app.actor_person_id', '019f0000-0000-7000-8000-00000000c0de', true);

create temporary table wave_movement (ordinal integer, slug text, discipline text, name text) on commit drop;
insert into wave_movement (ordinal, slug, discipline, name) values
${movements};

alter table wave_movement add column id uuid;
update wave_movement set id = ('019f1000-0000-7000-8000-' || lpad(ordinal::text, 12, '0'))::uuid;

insert into catalog.movements (id, discipline_code, name, normalized_name, content_scope, status)
select id, discipline, name, lower(name), 'global', 'published' from wave_movement
on conflict do nothing;

create temporary table wave_alias (movement_slug text, names text[]) on commit drop;
insert into wave_alias (movement_slug, names) values
${aliases};

insert into catalog.movement_aliases (id, movement_id, locale, name)
select
  extensions.uuid_generate_v7(), movement.id, 'es', alias.name
from wave_alias as row
join wave_movement as movement on movement.slug = row.movement_slug
cross join lateral unnest(row.names) as alias(name)
on conflict do nothing;

create temporary table wave_muscle (movement_slug text, muscle_codes text[]) on commit drop;
insert into wave_muscle (movement_slug, muscle_codes) values
${muscles};

insert into catalog.movement_muscles (id, movement_id, muscle_id, is_primary)
select
  extensions.uuid_generate_v7(),
  movement.id,
  muscle.id,
  chosen.position = 1
from wave_muscle as row
join wave_movement as movement on movement.slug = row.movement_slug
cross join lateral unnest(row.muscle_codes) with ordinality as chosen(code, position)
join catalog.muscles as muscle on muscle.code = chosen.code
on conflict do nothing;

create temporary table wave_equipment (movement_slug text, equipment_codes text[]) on commit drop;
insert into wave_equipment (movement_slug, equipment_codes) values
${equipment};

insert into catalog.movement_equipment (id, movement_id, equipment_id)
select
  extensions.uuid_generate_v7(), movement.id, item.id
from wave_equipment as row
join wave_movement as movement on movement.slug = row.movement_slug
cross join lateral unnest(row.equipment_codes) as needed(code)
join catalog.equipment as item on item.code = needed.code
on conflict do nothing;

create temporary table wave_step (movement_slug text, position integer, text text) on commit drop;
insert into wave_step (movement_slug, position, text) values
${steps};

insert into catalog.movement_instructions (id, movement_id, locale, position, text)
select
  extensions.uuid_generate_v7(), movement.id, 'es', step.position, step.text
from wave_step as step
join wave_movement as movement on movement.slug = step.movement_slug
on conflict do nothing;

commit;
`
}

async function main(): Promise<void> {
  const chosen = ((await Bun.file(here('wave.json')).json()) as { chosen: readonly Chosen[] })
    .chosen
  const written = everyAuthored()

  const byId = new Map(written.map((one) => [one.id, one]))
  const pending = chosen.filter((one) => !byId.has(one.exerciseId))
  if (pending.length > 0) {
    console.log(`${pending.length} of ${chosen.length} still to write:\n`)
    for (const one of pending) console.log(`  ${one.exerciseId}|${one.source}|${one.bodyPart}`)
    return
  }

  const rows = join(chosen, written)
  await Bun.write(CURATION, render(rows))
  console.log(
    `${rows.length} movements, ordinals ${rows[0]?.ordinal}–${rows[rows.length - 1]?.ordinal}`,
  )
}

if (import.meta.main) await main()
