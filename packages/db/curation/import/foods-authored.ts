interface Common {
  readonly name: string
  readonly icon: FoodIcon
  readonly aliases?: readonly string[]
  readonly portions: readonly Portion[]
  readonly approximate?: string
}

export interface UsdaFood extends Common {
  readonly usda: string
}

export interface RecipeFood extends Common {
  readonly recipe: readonly { readonly part: string; readonly grams: number }[]
}

export type AuthoredFood = UsdaFood | RecipeFood

const p = (label: string, grams: number, isDefault = false): Portion => ({
  label,
  grams,
  isDefault,
})

