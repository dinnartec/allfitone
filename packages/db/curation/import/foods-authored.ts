/**
 * The food catalogue as a person wrote it (ADR-041): the Spanish name, its synonyms, the
 * portions people in Colombia use, and which USDA FoodData Central food it is.
 *
 * **No nutrient is written here.** `usda` names a food by its exact SR Legacy description,
 * and `foods.ts` takes its values from the USDA files; a description that is not found
 * stops the run. Dishes are Allfit's recipes: their parts and grams are authored here,
 * and their nutrients are the sum of their parts, computed, never typed.
 *
 * Where USDA has no exact Colombian food the closest one is used and marked
 * `approximate`, for a nutritionist to review: those are estimates, and say so.
 */

export interface Portion {
  readonly label: string
  readonly grams: number
  readonly isDefault?: boolean
}

